
def area(a):
    """
    Считает площадь квадрата по длине стороны a.
    Формула: S = a²

    Пример вызова:
        >>> area(5)
        25
    """
    return a * a


def perimeter(a):
    """
    Считает периметр квадрата по длине стороны a.
    Формула: P = 4a

    Пример вызова:
        >>> perimeter(5)
        20
    """
    return 4 * a
